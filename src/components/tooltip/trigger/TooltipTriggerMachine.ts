import { getStyleHookProps } from '~@attributes/getStyleHookProps';
import { triggerOpenStateMapping } from '~@attributes/popupStateMapping';
import { OPEN_DELAY } from '~@lib/constants';
import { warn } from '~@lib/warn';
import { createDefaultDelayGroup, DelayGroupMember } from '~@packages/floating-ui/FloatingDelayGroup';
import { FocusInteraction } from '~@packages/floating-ui/interactions/FocusInteraction';
import { HoverReferenceInteraction } from '~@packages/floating-ui/interactions/hover/HoverReferenceInteraction';
import { safePolygon } from '~@packages/floating-ui/safePolygon';
import { Effect } from '~@packages/floating-ui/utils/Effect';
import { PopupTriggerRegistration } from '~@popup/popupTriggers';
import { mergeProps } from '~@props/mergeProps';

import type { FloatingDelayGroup } from '~@packages/floating-ui/FloatingDelayGroup';
import type { FloatingRootStore } from '~@packages/floating-ui/FloatingRootStore';
import type { FloatingTreeStore } from '~@packages/floating-ui/FloatingTreeStore';
import type { Props } from '~@props/mergeProps';

import { multipleSafePolygon } from '../multiple/multipleSafePolygon';
import { selectTooltipMultipleActive } from '../store/TooltipMultipleStore';

import type { TooltipMultipleMachine } from '../multiple/TooltipMultipleMachine';
import type { TooltipState, TooltipStore } from '../store/TooltipStore';

import { TooltipTriggerDataAttributes } from './TooltipTriggerDataAttributes';

export type TooltipTriggerState = {
    open: boolean;
    multipleActive: boolean;
};

export type TooltipTriggerOptions<Payload> = {
    /**
     * ID of the trigger (generated by the adapter when not provided).
     */
    id: string;
    payload?: Payload | undefined;
    /**
     * Whether this trigger positions the popup when opened without an active trigger.
     * @default false
     */
    primary?: boolean | undefined;
    /**
     * Defaults to the root's `disabled`.
     */
    disabled?: boolean | undefined;
    delay?: number | undefined;
    closeDelay?: number | undefined;
};

export type TooltipTriggerSetup = {
    multiple?: TooltipMultipleMachine | null | undefined;
    /**
     * The delay group of the enclosing `Tooltip.Provider`.
     */
    delayGroup?: FloatingDelayGroup | null | undefined;
    /**
     * `delay` of the enclosing `Tooltip.Provider`.
     */
    providerDelay?: number | undefined;
    tree?: FloatingTreeStore | null | undefined;
};

/**
 * State machine of `Tooltip.Trigger`: registration, delay group membership,
 * hover and focus interactions and `Tooltip.Multiple` active tracking.
 */
export class TooltipTriggerMachine<Payload = unknown> {
    readonly store: TooltipStore<Payload>;

    private options: TooltipTriggerOptions<Payload>;

    private readonly setup: TooltipTriggerSetup;

    private readonly registration: PopupTriggerRegistration<TooltipState<Payload>>;

    private readonly delayGroup: FloatingDelayGroup;

    private element: HTMLElement | null = null;

    private floatingRoot: FloatingRootStore | null = null;

    private hover: HoverReferenceInteraction | null = null;

    private focus: FocusInteraction | null = null;

    private delayMember: DelayGroupMember | null = null;

    private delayMemberUnsubscribe: (() => void) | null = null;

    private mountedByThisTrigger = false;

    private readonly handleClose: ReturnType<typeof safePolygon>;

    private readonly primaryEffect = new Effect(() => this.registerPrimary());

    private readonly multipleEffect = new Effect(() => this.attachMultipleListeners());

    private readonly unsubscribe: () => void;

    constructor(store: TooltipStore<Payload>, options: TooltipTriggerOptions<Payload>, setup: TooltipTriggerSetup = {}) {
        this.store = store;
        this.options = options;
        this.setup = setup;
        this.delayGroup = setup.delayGroup ?? createDefaultDelayGroup();
        // Inside `Tooltip.Multiple`, the safe area spans all triggers and popups of the group.
        this.handleClose = setup.multiple ? multipleSafePolygon(setup.multiple.store) : safePolygon();
        this.registration = new PopupTriggerRegistration(store, options.id, this.getForwardedState());
        this.unsubscribe = store.subscribe(() => this.sync());
        this.sync();
    }

    setOptions(options: TooltipTriggerOptions<Payload>) {
        const forwardedChanged = options.payload !== this.options.payload || options.closeDelay !== this.options.closeDelay;
        this.options = options;
        this.registration.setOptions(options.id, this.getForwardedState());
        if (forwardedChanged) {
            this.registration.sync();
        }
        this.sync();
    }

    setElement = (element: HTMLElement | null) => {
        this.element = element;
        this.registration.setElement(element);
        this.sync();
    };

    getState(): TooltipTriggerState {
        return {
            open: this.store.select('isOpenedByTrigger', this.options.id),
            multipleActive: selectTooltipMultipleActive(this.store as TooltipStore<unknown>, this.setup.multiple?.store ?? null)
        };
    }

    static attrs(state: TooltipTriggerState) {
        return getStyleHookProps(state, triggerOpenStateMapping);
    }

    getTriggerProps(elementProps: Props = {}): Props {
        const disabled = this.disabled;
        return mergeProps(
            this.hover?.getProps(),
            this.focus?.getProps().reference as Props | undefined,
            this.store.select('triggerProps', this.mountedByThisTrigger),
            { id: this.options.id, [TooltipTriggerDataAttributes.triggerDisabled]: disabled ? '' : undefined },
            elementProps
        );
    }

    destroy() {
        this.unsubscribe();
        this.registration.destroy();
        this.primaryEffect.destroy();
        this.multipleEffect.destroy();
        this.destroyInteractions();
    }

    private get disabled() {
        return this.options.disabled ?? this.store.select('disabled');
    }

    private get delayWithDefault() {
        return this.options.delay ?? this.setup.multiple?.delay ?? OPEN_DELAY;
    }

    private get closeDelayWithDefault() {
        return this.options.closeDelay ?? this.setup.multiple?.closeDelay ?? 0;
    }

    private getForwardedState() {
        return { payload: this.options.payload, closeDelay: this.closeDelayWithDefault } as Partial<TooltipState<Payload>>;
    }

    private registerPrimary() {
        const { primary = false, id } = this.options;
        const { store } = this;
        if (!primary) {
            return;
        }

        const currentPrimaryId = store.select('primaryTriggerId');
        // First wins: if there's already a primary, warn and ignore.
        if (currentPrimaryId !== null && currentPrimaryId !== id) {
            warn(
                `Tooltip: multiple triggers marked as primary. Trigger "${currentPrimaryId}" is already primary. Ignoring primary on trigger "${id}".`
            );
            return;
        }

        store.set('primaryTriggerId', id);
        return () => {
            if (store.select('primaryTriggerId') === id) {
                store.set('primaryTriggerId', null);
            }
        };
    }

    private attachMultipleListeners() {
        const multiple = this.setup.multiple;
        const index = this.store.select('multipleItemIndex');
        const element = this.element;
        if (!element || !multiple || index == null || index < 0) {
            return;
        }

        const onSetActive = () => multiple.store.set('activeIndex', index);
        const onSetInactive = () => multiple.store.set('activeIndex', null);

        element.addEventListener('mouseenter', onSetActive);
        element.addEventListener('mouseleave', onSetInactive);
        element.addEventListener('focus', onSetActive);
        element.addEventListener('blur', onSetInactive);
        return () => {
            element.removeEventListener('mouseenter', onSetActive);
            element.removeEventListener('mouseleave', onSetInactive);
            element.removeEventListener('focus', onSetActive);
            element.removeEventListener('blur', onSetInactive);
        };
    }

    private getHoverOptions() {
        const { store } = this;
        const trackCursorAxis = store.select('trackCursorAxis');
        const disableHoverablePopup = store.select('disableHoverablePopup');

        return {
            enabled: !this.disabled,
            mouseOnly: true,
            move: false,
            handleClose: !disableHoverablePopup && trackCursorAxis !== 'both' ? this.handleClose : null,
            restMs: () => {
                const delayRef = this.delayGroup.delayRef;
                const groupOpenValue = typeof delayRef.current === 'object' ? delayRef.current.open : undefined;
                if (!this.delayGroup.hasProvider) {
                    return this.delayWithDefault;
                }
                return groupOpenValue === 0 ? 0 : (this.options.delay ?? this.setup.providerDelay ?? this.delayWithDefault);
            },
            delay: () => {
                const delayRef = this.delayGroup.delayRef;
                const closeValue = typeof delayRef.current === 'object' ? delayRef.current.close : undefined;
                const close = this.options.closeDelay == null && this.delayGroup.hasProvider ? closeValue : this.closeDelayWithDefault;
                return { close };
            },
            triggerElement: this.element,
            isActiveTrigger: store.select('isTriggerActive', this.options.id),
            tree: this.setup.tree,
            flushSync: store.context.flushSync
        };
    }

    private sync() {
        const floatingRoot = this.store.select('floatingRootContext');
        const isOpenedByThisTrigger = this.store.select('isOpenedByTrigger', this.options.id);

        if (floatingRoot !== this.floatingRoot) {
            this.destroyInteractions();
            this.floatingRoot = floatingRoot;
            this.hover = new HoverReferenceInteraction(floatingRoot, this.getHoverOptions());
            this.focus = new FocusInteraction(floatingRoot, { enabled: !this.disabled });
            const member = new DelayGroupMember(floatingRoot, this.delayGroup, { open: isOpenedByThisTrigger });
            this.delayMember = member;
            this.delayMemberUnsubscribe = member.state.subscribe(() => {
                this.store.syncValue('isInstantPhase', member.state.state.isInstantPhase);
            });
            this.store.syncValue('isInstantPhase', member.state.state.isInstantPhase);
        } else {
            this.hover?.setOptions(this.getHoverOptions());
            this.focus?.setOptions({ enabled: !this.disabled });
            this.delayMember?.setOptions({ open: isOpenedByThisTrigger });
        }

        const mounted = this.registration.isMountedByThisTrigger();
        if (mounted !== this.mountedByThisTrigger) {
            this.mountedByThisTrigger = mounted;
            if (mounted) {
                this.registration.sync();
            }
        }

        this.primaryEffect.sync([this.options.primary, this.options.id]);
        this.multipleEffect.sync([this.element, this.store.select('multipleItemIndex')]);
    }

    private destroyInteractions() {
        this.hover?.destroy();
        this.focus?.destroy();
        this.delayMemberUnsubscribe?.();
        this.delayMember?.destroy();
        this.hover = null;
        this.focus = null;
        this.delayMember = null;
        this.delayMemberUnsubscribe = null;
    }
}
