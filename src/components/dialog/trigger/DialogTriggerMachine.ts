import { getStyleHookProps } from '~@attributes/getStyleHookProps';
import { triggerOpenStateMapping } from '~@attributes/popupStateMapping';
import { ButtonMachine } from '~@components/button/root/ButtonMachine';
import { CLICK_TRIGGER_IDENTIFIER } from '~@lib/constants';
import { ClickInteraction } from '~@packages/floating-ui/interactions/ClickInteraction';
import { mergeInteractionProps } from '~@packages/floating-ui/interactions/mergeInteractionProps';
import { PopupTriggerRegistration } from '~@popup/popupTriggers';
import { mergeProps } from '~@props/mergeProps';

import type { FloatingRootStore } from '~@packages/floating-ui/FloatingRootStore';
import type { Props } from '~@props/mergeProps';

import type { DialogState, DialogStore } from '../store/DialogStore';

export type DialogTriggerState = {
    disabled: boolean;
    open: boolean;
};

export type DialogTriggerOptions<Payload> = {
    /**
     * ID of the trigger (generated by the adapter when not provided).
     */
    id: string;
    /**
     * @default false
     */
    disabled?: boolean | undefined;
    /**
     * @default true
     */
    nativeButton?: boolean | undefined;
    payload?: Payload | undefined;
};

/**
 * State machine of `Dialog.Trigger`.
 */
export class DialogTriggerMachine<Payload = unknown> {
    readonly button: ButtonMachine;

    private options: DialogTriggerOptions<Payload>;

    private readonly store: DialogStore<Payload>;

    private readonly registration: PopupTriggerRegistration<DialogState<Payload>>;

    private floatingRoot: FloatingRootStore | null = null;

    private click: ClickInteraction | null = null;

    private mountedByThisTrigger = false;

    private readonly unsubscribe: () => void;

    constructor(store: DialogStore<Payload>, options: DialogTriggerOptions<Payload>) {
        this.store = store;
        this.options = options;
        this.button = new ButtonMachine({ disabled: options.disabled, native: options.nativeButton });
        this.registration = new PopupTriggerRegistration(store, options.id, this.getForwardedState());
        this.unsubscribe = store.subscribe(() => this.sync());
        this.sync();
    }

    setOptions(options: DialogTriggerOptions<Payload>) {
        const payloadChanged = options.payload !== this.options.payload;
        this.options = options;
        this.button.setOptions({ disabled: options.disabled, native: options.nativeButton });
        this.registration.setOptions(options.id, this.getForwardedState());
        if (payloadChanged) {
            this.registration.sync();
        }
        this.sync();
    }

    setElement = (element: HTMLElement | null) => {
        this.button.setElement(element);
        this.registration.setElement(element);
        this.sync();
    };

    getState(): DialogTriggerState {
        return { disabled: this.options.disabled ?? false, open: this.store.select('isOpenedByTrigger', this.options.id) };
    }

    static attrs(state: DialogTriggerState) {
        return getStyleHookProps(state, triggerOpenStateMapping);
    }

    getTriggerProps(elementProps: Props = {}): Props {
        return mergeProps(
            this.click ? mergeInteractionProps(undefined, [this.click.getProps()], 'reference') : undefined,
            this.store.select('triggerProps', this.mountedByThisTrigger),
            { [CLICK_TRIGGER_IDENTIFIER]: '', id: this.options.id },
            elementProps,
            (props: Props) => this.button.getButtonProps(props)
        );
    }

    destroy() {
        this.unsubscribe();
        this.registration.destroy();
        this.click?.destroy();
        this.click = null;
    }

    private getForwardedState() {
        return { payload: this.options.payload } as Partial<DialogState<Payload>>;
    }

    private sync() {
        const floatingRoot = this.store.select('floatingRootContext');
        if (floatingRoot !== this.floatingRoot) {
            this.click?.destroy();
            this.floatingRoot = floatingRoot;
            this.click = new ClickInteraction(floatingRoot);
        }

        const mounted = this.registration.isMountedByThisTrigger();
        if (mounted !== this.mountedByThisTrigger) {
            this.mountedByThisTrigger = mounted;
            if (mounted) {
                this.registration.sync();
            }
        }
    }
}
