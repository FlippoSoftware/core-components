import { MixedToggleClickHandler } from '../utils/MixedToggleClickHandler';

import type { MenuKeyboardEventRelay, MenuParent, MenuState, MenuStore } from '../store/MenuStore';

const BOUNDARY_OFFSET = 2;

export type MenuTriggerState = {
    disabled: boolean;
    open: boolean;
};

export type MenuTriggerOptions<Payload> = {
    /**
     * ID of the trigger (generated by the adapter when not provided).
     */
    id: string;
    /**
     * @default false
     */
    disabled?: boolean | undefined;
    /**
     * @default true
     */
    nativeButton?: boolean | undefined;
    /**
     * Defaults to whether the parent menubar has a submenu open.
     */
    openOnHover?: boolean | undefined;
    /**
     * @default 100
     */
    delay?: number | undefined;
    /**
     * @default 0
     */
    closeDelay?: number | undefined;
    payload?: Payload | undefined;
};

export type MenuTriggerSetup = {
    /**
     * The menubar or context menu the trigger is in (`{ type: undefined }` otherwise).
     */
    parent?: MenuParent | undefined;
    /**
     * Relays keyboard events of a detached menu to the menubar's composite root.
     */
    keyboardEventRelay?: MenuKeyboardEventRelay | undefined;
};

type FocusLikeEvent = FocusEvent | { nativeEvent: FocusEvent; currentTarget: EventTarget | null };

/**
 * State machine of `Menu.Trigger`: registration (forwarding the parent and tree to the menu),
 * click/hover/focus interactions, the "press, drag and release on an item" gesture and the focus guards.
 */
export class MenuTriggerMachine<Payload = unknown> {
    readonly button: ButtonMachine;

    private options: MenuTriggerOptions<Payload>;

    private readonly setup: MenuTriggerSetup;

    private readonly store: MenuStore<Payload>;

    private readonly registration: PopupTriggerRegistration<MenuState<Payload>>;

    private element: HTMLElement | null = null;

    private preFocusGuard: HTMLElement | null = null;

    private floatingRoot: FloatingRootStore | null = null;

    private click: ClickInteraction | null = null;

    private hover: HoverReferenceInteraction | null = null;

    private focus: FocusInteraction | null = null;

    private mountedByThisTrigger = false;

    private stickIfOpen = false;

    private readonly stickIfOpenTimeout = new Timeout();

    private readonly allowMouseUpTriggerTimeout = new Timeout();

    private readonly mixedToggle = new MixedToggleClickHandler();

    private readonly handleClose: ReturnType<typeof safePolygon>;

    private readonly openedByThisTriggerEffect = new Effect(() => this.handleOpenedByThisTrigger());

    private readonly unsubscribe: () => void;

    constructor(store: MenuStore<Payload>, options: MenuTriggerOptions<Payload>, setup: MenuTriggerSetup = {}) {
        this.store = store;
        this.options = options;
        this.setup = setup;
        this.handleClose = safePolygon({ blockPointerEvents: this.parent.type !== 'menubar' });
        this.button = new ButtonMachine({ disabled: this.disabled, native: options.nativeButton });
        this.registration = new PopupTriggerRegistration(store, options.id, this.getForwardedState());
        this.unsubscribe = store.subscribe(() => this.sync());
        this.sync();
    }

    setOptions(options: MenuTriggerOptions<Payload>) {
        const forwardedChanged = options.payload !== this.options.payload || options.closeDelay !== this.options.closeDelay;
        this.options = options;
        this.button.setOptions({ disabled: this.disabled, native: options.nativeButton });
        this.registration.setOptions(options.id, this.getForwardedState());
        if (forwardedChanged) {
            this.registration.sync();
        }
        this.sync();
    }

    setElement = (element: HTMLElement | null) => {
        this.element = element;
        this.button.setElement(element);
        this.registration.setElement(element);
        this.sync();
    };

    getState(): MenuTriggerState {
        return { disabled: this.disabled, open: this.isOpenedByThisTrigger };
    }

    static attrs(state: MenuTriggerState) {
        return getStyleHookProps(state, pressableTriggerOpenStateMapping);
    }

    /**
     * Whether the adapter renders the trigger as a composite item of the menubar.
     */
    get isInMenubar(): boolean {
        return this.parent.type === 'menubar';
    }

    /**
     * Whether the adapter renders the focus guards around the trigger.
     */
    shouldRenderFocusGuards(): boolean {
        return !this.isInMenubar && this.isOpenedByThisTrigger;
    }

    getTriggerProps(elementProps: Props = {}): Props {
        const interactionProps = mergeInteractionProps(undefined, [this.click?.getProps(), this.focus?.getProps()], 'reference');

        return mergeProps(
            interactionProps,
            this.hover?.getProps(),
            this.store.select('triggerProps', this.mountedByThisTrigger),
            {
                'aria-haspopup': 'menu',
                id: this.options.id,
                onMouseDown: (event: MouseEvent | { currentTarget: EventTarget | null }) => {
                    if (this.store.select('open')) {
                        return;
                    }
                    // mousedown -> mouseup on a menu item should not trigger it within 200ms.
                    this.allowMouseUpTriggerTimeout.start(200, () => {
                        this.store.context.allowMouseUpTriggerRef.current = true;
                    });
                    ownerDocument(event.currentTarget as Element | null).addEventListener('mouseup', this.handleDocumentMouseUp, {
                        once: true
                    });
                }
            },
            this.isInMenubar ? { role: 'menuitem' } : {},
            this.isInMenubar ? this.mixedToggle.getProps(this.isOpenedByThisTrigger, 'open') : undefined,
            elementProps,
            (props: Props) => this.button.getButtonProps(props)
        );
    }

    setPreFocusGuard = (element: HTMLElement | null) => {
        this.preFocusGuard = element;
    };

    setFocusTarget = (element: HTMLElement | null) => {
        this.store.context.triggerFocusTargetRef.current = element;
    };

    onPreFocusGuardFocus = (event: FocusLikeEvent) => {
        this.closeOnFocusOut(event);
        getTabbableBeforeElement(this.preFocusGuard)?.focus();
    };

    onFocusTargetFocus = (event: FocusLikeEvent) => {
        const positionerElement = this.store.select('positionerElement');
        if (positionerElement && isOutsideEvent(getNativeEvent(event as FocusEvent), positionerElement)) {
            this.store.context.beforeContentFocusGuardRef.current?.focus();
            return;
        }

        this.closeOnFocusOut(event);
        let nextTabbable = getTabbableAfterElement(this.store.context.triggerFocusTargetRef.current || this.element);
        while (nextTabbable !== null && contains(positionerElement, nextTabbable)) {
            const prevTabbable = nextTabbable;
            nextTabbable = getNextTabbable(nextTabbable);
            if (nextTabbable === prevTabbable) {
                break;
            }
        }
        nextTabbable?.focus();
    };

    destroy() {
        this.unsubscribe();
        this.registration.destroy();
        this.openedByThisTriggerEffect.destroy();
        this.stickIfOpenTimeout.clear();
        this.allowMouseUpTriggerTimeout.clear();
        this.destroyInteractions();
    }

    private get parent(): MenuParent {
        return this.setup.parent ?? { type: undefined };
    }

    private get disabled(): boolean {
        const parent = this.parent;
        return (
            (this.options.disabled ?? false) ||
            (this.store?.select('disabled') ?? false) ||
            (parent.type === 'menubar' && parent.context.disabled)
        );
    }

    private get isOpenedByThisTrigger(): boolean {
        return this.store.select('isOpenedByTrigger', this.options.id);
    }

    private get parentMenubarHasSubmenuOpen(): boolean {
        const parent = this.parent;
        return parent.type === 'menubar' && Boolean(parent.context.hasSubmenuOpen);
    }

    private getForwardedState() {
        const parent = this.parent;
        const updates: Partial<MenuState<Payload>> = {
            payload: this.options.payload,
            closeDelay: this.options.closeDelay ?? 0,
            parent,
            keyboardEventRelay: this.setup.keyboardEventRelay
        };
        if (parent.type === 'menubar' && parent.context.tree) {
            updates.floatingTreeRoot = parent.context.tree;
        }
        return updates;
    }

    private closeOnFocusOut(event: FocusLikeEvent) {
        const nativeEvent = getNativeEvent(event as FocusEvent);
        const currentTarget = ('currentTarget' in event ? event.currentTarget : nativeEvent.currentTarget) as HTMLElement;
        this.store.setOpen(false, createChangeEventDetails(REASONS.focusOut, nativeEvent, currentTarget));
    }

    private readonly handleDocumentMouseUp = (mouseEvent: MouseEvent) => {
        const trigger = this.element;
        if (!trigger) {
            return;
        }

        this.allowMouseUpTriggerTimeout.clear();
        this.store.context.allowMouseUpTriggerRef.current = false;

        const mouseUpTarget = mouseEvent.target as Element | null;
        if (
            contains(trigger, mouseUpTarget) ||
            contains(this.store.select('positionerElement'), mouseUpTarget) ||
            mouseUpTarget === trigger
        ) {
            return;
        }
        if (mouseUpTarget != null && findRootOwnerId(mouseUpTarget) === this.store.select('rootId')) {
            return;
        }

        const bounds = getPseudoElementBounds(trigger);
        if (
            mouseEvent.clientX >= bounds.left - BOUNDARY_OFFSET &&
            mouseEvent.clientX <= bounds.right + BOUNDARY_OFFSET &&
            mouseEvent.clientY >= bounds.top - BOUNDARY_OFFSET &&
            mouseEvent.clientY <= bounds.bottom + BOUNDARY_OFFSET
        ) {
            return;
        }

        this.store.select('floatingTreeRoot').events.emit('close', { domEvent: mouseEvent, reason: REASONS.cancelOpen });
    };

    private handleOpenedByThisTrigger() {
        const open = this.isOpenedByThisTrigger;
        const reason = this.store.select('lastOpenChangeReason');

        if (!open && this.parent.type === undefined) {
            this.store.context.allowMouseUpTriggerRef.current = false;
        }

        // Only allow "patient" clicks to close the menu if it was opened by hover.
        if (open && reason === REASONS.triggerHover) {
            this.stickIfOpen = true;
            this.stickIfOpenTimeout.start(PATIENT_CLICK_THRESHOLD, () => {
                this.stickIfOpen = false;
                this.click?.setOptions(this.getClickOptions());
            });
            ownerDocument(this.element).addEventListener('mouseup', this.handleDocumentMouseUp, { once: true });
        } else if (!open) {
            this.stickIfOpenTimeout.clear();
            this.stickIfOpen = false;
        }
    }

    private getClickOptions() {
        const parent = this.parent;
        return {
            enabled: !this.disabled && parent.type !== 'context-menu',
            event: this.isOpenedByThisTrigger && this.isInMenubar ? ('click' as const) : ('mousedown' as const),
            toggle: true,
            ignoreMouse: false,
            stickIfOpen: parent.type === undefined ? this.stickIfOpen : false
        };
    }

    private getHoverOptions() {
        const parent = this.parent;
        const hasSubmenuOpen = this.parentMenubarHasSubmenuOpen;
        const openOnHover = this.options.openOnHover ?? hasSubmenuOpen;
        return {
            enabled:
                openOnHover &&
                !this.disabled &&
                parent.type !== 'context-menu' &&
                (!this.isInMenubar || (hasSubmenuOpen && !this.mountedByThisTrigger)),
            handleClose: this.handleClose,
            mouseOnly: true,
            move: false,
            restMs: parent.type === undefined ? (this.options.delay ?? 100) : undefined,
            delay: { close: this.options.closeDelay ?? 0 },
            triggerElement: this.element,
            tree: this.store.select('floatingTreeRoot'),
            isActiveTrigger: this.store.select('isTriggerActive', this.options.id)
        };
    }

    private sync() {
        const floatingRoot = this.store.select('floatingRootContext');
        if (floatingRoot !== this.floatingRoot) {
            this.destroyInteractions();
            this.floatingRoot = floatingRoot;
            this.click = new ClickInteraction(floatingRoot, this.getClickOptions());
            this.hover = new HoverReferenceInteraction(floatingRoot, this.getHoverOptions());
            this.focus = new FocusInteraction(floatingRoot, { enabled: !this.disabled && this.parentMenubarHasSubmenuOpen });
        } else {
            this.click?.setOptions(this.getClickOptions());
            this.hover?.setOptions(this.getHoverOptions());
            this.focus?.setOptions({ enabled: !this.disabled && this.parentMenubarHasSubmenuOpen });
        }

        this.button.setOptions({ disabled: this.disabled, native: this.options.nativeButton });
        this.openedByThisTriggerEffect.sync([this.isOpenedByThisTrigger]);

        const mounted = this.registration.isMountedByThisTrigger();
        if (mounted !== this.mountedByThisTrigger) {
            this.mountedByThisTrigger = mounted;
            if (mounted) {
                this.registration.sync();
            }
        }
    }

    private destroyInteractions() {
        this.click?.destroy();
        this.hover?.destroy();
        this.focus?.destroy();
        this.click = null;
        this.hover = null;
        this.focus = null;
    }
}
