import { getStyleHookProps } from '~@attributes/getStyleHookProps';
import { pressableTriggerOpenStateMapping, triggerOpenStateMapping } from '~@attributes/popupStateMapping';
import { ButtonMachine } from '~@components/button/root/ButtonMachine';
import { createChangeEventDetails } from '~@events/changeEventDetails';
import { REASONS } from '~@events/reasons';
import { CLICK_TRIGGER_IDENTIFIER, OPEN_DELAY } from '~@lib/constants';
import { ClickInteraction } from '~@packages/floating-ui/interactions/ClickInteraction';
import { HoverReferenceInteraction } from '~@packages/floating-ui/interactions/hover/HoverReferenceInteraction';
import { mergeInteractionProps } from '~@packages/floating-ui/interactions/mergeInteractionProps';
import { safePolygon } from '~@packages/floating-ui/safePolygon';
import { contains } from '~@packages/floating-ui/utils/element';
import { getNativeEvent } from '~@packages/floating-ui/utils/event';
import { getNextTabbable, getTabbableAfterElement, getTabbableBeforeElement, isOutsideEvent } from '~@packages/floating-ui/utils/tabbable';
import { PopupTriggerRegistration } from '~@popup/popupTriggers';
import { mergeProps } from '~@props/mergeProps';

import type { FloatingRootStore } from '~@packages/floating-ui/FloatingRootStore';
import type { FloatingTreeStore } from '~@packages/floating-ui/FloatingTreeStore';
import type { Props } from '~@props/mergeProps';

import type { PopoverState, PopoverStore } from '../store/PopoverStore';

export type PopoverTriggerState = {
    disabled: boolean;
    open: boolean;
};

export type PopoverTriggerOptions<Payload> = {
    /**
     * ID of the trigger (generated by the adapter when not provided).
     */
    id: string;
    /**
     * @default false
     */
    disabled?: boolean | undefined;
    /**
     * @default true
     */
    nativeButton?: boolean | undefined;
    payload?: Payload | undefined;
    /**
     * @default false
     */
    openOnHover?: boolean | undefined;
    /**
     * @default 500
     */
    delay?: number | undefined;
    /**
     * @default 0
     */
    closeDelay?: number | undefined;
    tree?: FloatingTreeStore | null | undefined;
};

type FocusLikeEvent = FocusEvent | { nativeEvent: FocusEvent; currentTarget: EventTarget | null };

/**
 * State machine of `Popover.Trigger`: registration in the popover, click and hover interactions,
 * and the focus guards rendered around the active trigger.
 */
export class PopoverTriggerMachine<Payload = unknown> {
    readonly store: PopoverStore<Payload>;

    readonly button: ButtonMachine;

    private options: PopoverTriggerOptions<Payload>;

    private readonly registration: PopupTriggerRegistration<PopoverState<Payload>>;

    private element: HTMLElement | null = null;

    private preFocusGuard: HTMLElement | null = null;

    private floatingRoot: FloatingRootStore | null = null;

    private click: ClickInteraction | null = null;

    private hover: HoverReferenceInteraction | null = null;

    private mountedByThisTrigger = false;

    private readonly handleClose = safePolygon();

    private readonly unsubscribe: () => void;

    constructor(store: PopoverStore<Payload>, options: PopoverTriggerOptions<Payload>) {
        this.store = store;
        this.options = options;
        this.button = new ButtonMachine({ disabled: options.disabled, native: options.nativeButton });
        this.registration = new PopupTriggerRegistration(store, options.id, this.getForwardedState());
        this.unsubscribe = store.subscribe(() => this.sync());
        this.sync();
    }

    setOptions(options: PopoverTriggerOptions<Payload>) {
        const forwardedChanged =
            options.payload !== this.options.payload ||
            options.disabled !== this.options.disabled ||
            options.openOnHover !== this.options.openOnHover ||
            options.closeDelay !== this.options.closeDelay;

        this.options = options;
        this.button.setOptions({ disabled: options.disabled, native: options.nativeButton });
        this.registration.setOptions(options.id, this.getForwardedState());

        if (forwardedChanged) {
            this.registration.sync();
        }
        this.sync();
    }

    /**
     * Ref callback for the trigger element.
     */
    setElement = (element: HTMLElement | null) => {
        this.element = element;
        this.button.setElement(element);
        this.registration.setElement(element);
        this.sync();
    };

    /**
     * Whether this trigger is the active one; the adapter renders the focus guards around it then.
     */
    isActive(): boolean {
        return this.store.select('isTriggerActive', this.options.id);
    }

    getState(): PopoverTriggerState {
        return {
            disabled: this.options.disabled ?? false,
            open: this.store.select('isOpenedByTrigger', this.options.id)
        };
    }

    /**
     * Data attributes for the given state (`data-pressed` is only set when opened by a press).
     */
    getStateAttributes(state: PopoverTriggerState = this.getState()) {
        const openMapping =
            this.store.select('openChangeReason') === REASONS.triggerPress ? pressableTriggerOpenStateMapping : triggerOpenStateMapping;
        return getStyleHookProps(state, openMapping);
    }

    getTriggerProps(elementProps: Props = {}): Props {
        const clickProps = this.click ? mergeInteractionProps(undefined, [this.click.getProps()], 'reference') : undefined;

        return mergeProps(
            clickProps,
            this.hover?.getProps(),
            this.store.select('triggerProps', this.mountedByThisTrigger),
            { [CLICK_TRIGGER_IDENTIFIER]: '', id: this.options.id },
            elementProps,
            (props: Props) => this.button.getButtonProps(props)
        );
    }

    /**
     * Ref callback for the focus guard rendered before the active trigger.
     */
    setPreFocusGuard = (element: HTMLElement | null) => {
        this.preFocusGuard = element;
    };

    /**
     * Ref callback for the focus guard rendered after the active trigger.
     */
    setFocusTarget = (element: HTMLElement | null) => {
        this.store.context.triggerFocusTargetRef.current = element;
    };

    /**
     * Focus handler of the guard before the active trigger.
     */
    onPreFocusGuardFocus = (event: FocusLikeEvent) => {
        this.closeOnFocusOut(event);
        getTabbableBeforeElement(this.preFocusGuard)?.focus();
    };

    /**
     * Focus handler of the guard after the active trigger.
     */
    onFocusTargetFocus = (event: FocusLikeEvent) => {
        const positionerElement = this.store.select('positionerElement');
        const nativeEvent = getNativeEvent(event as FocusEvent);

        if (positionerElement && isOutsideEvent(nativeEvent, positionerElement)) {
            this.store.context.beforeContentFocusGuardRef.current?.focus();
            return;
        }

        this.closeOnFocusOut(event);

        let nextTabbable = getTabbableAfterElement(this.store.context.triggerFocusTargetRef.current || this.element);
        while (nextTabbable !== null && contains(positionerElement, nextTabbable)) {
            const prevTabbable = nextTabbable;
            nextTabbable = getNextTabbable(nextTabbable);
            if (nextTabbable === prevTabbable) {
                break;
            }
        }
        nextTabbable?.focus();
    };

    destroy() {
        this.unsubscribe();
        this.registration.destroy();
        this.destroyInteractions();
    }

    private closeOnFocusOut(event: FocusLikeEvent) {
        const nativeEvent = getNativeEvent(event as FocusEvent);
        const currentTarget = ('currentTarget' in event ? event.currentTarget : nativeEvent.currentTarget) as HTMLElement;
        this.store.context.flushSync(() => {
            this.store.setOpen(false, createChangeEventDetails(REASONS.focusOut, nativeEvent, currentTarget));
        });
    }

    private getForwardedState() {
        const { payload, disabled = false, openOnHover = false, closeDelay = 0 } = this.options;
        return { payload, disabled, openOnHover, closeDelay } as Partial<PopoverState<Payload>>;
    }

    private sync() {
        const floatingRoot = this.store.select('floatingRootContext');
        if (floatingRoot !== this.floatingRoot) {
            this.destroyInteractions();
            this.floatingRoot = floatingRoot;
            this.click = new ClickInteraction(floatingRoot, this.getClickOptions());
            this.hover = new HoverReferenceInteraction(floatingRoot, this.getHoverOptions());
        } else {
            this.click?.setOptions(this.getClickOptions());
            this.hover?.setOptions(this.getHoverOptions());
        }

        const mounted = this.registration.isMountedByThisTrigger();
        if (mounted !== this.mountedByThisTrigger) {
            this.mountedByThisTrigger = mounted;
            if (mounted) {
                this.registration.sync();
            }
        }
    }

    private getClickOptions() {
        return { stickIfOpen: this.store.select('stickIfOpen') };
    }

    private getHoverOptions() {
        const { openOnHover = false, delay = OPEN_DELAY, closeDelay = 0, tree } = this.options;
        const { store } = this;
        return {
            enabled: openOnHover && (store.select('openMethod') !== 'touch' || store.select('openChangeReason') !== REASONS.triggerPress),
            mouseOnly: true,
            move: false,
            handleClose: this.handleClose,
            restMs: delay,
            delay: { close: closeDelay },
            triggerElement: this.element,
            isActiveTrigger: this.isActive(),
            tree,
            flushSync: store.context.flushSync
        };
    }

    private destroyInteractions() {
        this.click?.destroy();
        this.hover?.destroy();
        this.click = null;
        this.hover = null;
    }
}
